/* HYPHSWORLD Casino Arcade — CPU mode clarity
   Makes it clear every game can be played solo against CPU / house mode.
*/
(function(){
  "use strict";

  var $ = function(q, r){ return (r || document).querySelector(q); };
  var $$ = function(q, r){ return Array.prototype.slice.call((r || document).querySelectorAll(q)); };

  var HELP = {
    crash: "CPU Mode: the rocket is the house. Set Entry Power, pick a target, then Play CPU Crash.",
    plinko: "CPU Mode: the board decides the path. Drop the ball and let the buckets decide the bonus.",
    mines: "CPU Mode: the house hides the mines. Open safe tiles, then cash out before a bomb appears.",
    slots: "CPU Mode: the reels spin for you. Match symbols to build reward progress.",
    scratcher: "CPU Mode: the card is generated by the house. Reveal all panels and match icons.",
    hilo: "CPU Mode: the house flips the next card. Guess higher or lower to build a streak.",
    roulette: "CPU Mode: the wheel spins against your color pick. Red/black are safer, green is rare.",
    blackjack: "CPU Mode: Duck Dealer plays the dealer hand. Deal, hit, or stand against Duck.",
    dominos: "CPU Mode: Duck, Buck, and CPU seats are already at the table. Play bones against the house table."
  };

  var BUTTON_TEXT = {
    "crash-play": "Play CPU Crash",
    "plinko-drop": "Play CPU Plinko",
    "mines-start": "Play CPU Mines",
    "mines-cashout": "Cash Out",
    "slots-spin": "Play CPU Slots",
    "scratch-new": "Play CPU Scratcher",
    "hilo-high": "CPU Flip: Higher",
    "hilo-low": "CPU Flip: Lower",
    "hilo-new": "New CPU Card",
    "roulette-spin": "Play CPU Roulette",
    "bj-deal": "Play CPU Dealer",
    "bj-hit": "Hit",
    "bj-stand": "Stand",
    "dom-new": "Play CPU Dominos",
    "dom-play": "Play Bone",
    "dom-draw": "Draw From CPU Boneyard"
  };

  function injectStyles(){
    if($("#casinoCpuModeStyles")) return;
    var style = document.createElement("style");
    style.id = "casinoCpuModeStyles";
    style.textContent = "\
      .cpu-mode-panel{margin:12px 0;padding:12px 13px;border-radius:18px;border:2px dashed rgba(57,255,122,.55);background:radial-gradient(circle at 0 0,rgba(255,79,216,.18),transparent 34%),rgba(0,0,0,.34);box-shadow:0 12px 26px rgba(0,0,0,.22)}\
      .cpu-mode-panel strong{display:block;color:#39ff7a;text-transform:uppercase;letter-spacing:.12em;font-size:12px;margin-bottom:4px}\
      .cpu-mode-panel span{display:block;color:#d8efe6;font-weight:900;line-height:1.35}\
      .cpu-mode-chip{display:inline-flex;align-items:center;gap:6px;margin-left:8px;padding:5px 8px;border-radius:999px;background:linear-gradient(135deg,#39ff7a,#ffe45c,#1ffcff);color:#050507;font-size:10px;font-weight:1000;letter-spacing:.08em;text-transform:uppercase;vertical-align:middle}\
      .casino-game-tile .cpu-mini{display:inline-block;margin-top:6px;padding:4px 7px;border-radius:999px;background:rgba(57,255,122,.18);color:#9fffd0;font-size:10px;font-weight:1000;letter-spacing:.08em;text-transform:uppercase}\
      .casino-game-tile.is-active .cpu-mini{background:rgba(0,0,0,.18);color:#050507}\
      @media(max-width:760px){.cpu-mode-panel{margin:10px 0 14px}.cpu-mode-chip{display:inline-flex;margin:6px 0 0 0}}\
    ";
    document.head.appendChild(style);
  }

  function activeGame(){
    var tile = $(".casino-game-tile.is-active");
    return tile && tile.dataset && tile.dataset.game ? tile.dataset.game : "crash";
  }

  function ensurePanel(){
    var desc = $("#casinoGameDescription");
    if(!desc) return null;
    var panel = $("#cpuModePanel");
    if(!panel){
      panel = document.createElement("div");
      panel.id = "cpuModePanel";
      panel.className = "cpu-mode-panel";
      desc.insertAdjacentElement("afterend", panel);
    }
    return panel;
  }

  function renderPanel(){
    var game = activeGame();
    var panel = ensurePanel();
    if(!panel) return;
    panel.innerHTML = '<strong>Solo / CPU Play Ready</strong><span>' + (HELP[game] || "CPU Mode: pick a game and press the play button. No second user required.") + '</span>';

    var title = $("#casinoGameTitle");
    if(title && !title.querySelector(".cpu-mode-chip")){
      var chip = document.createElement("small");
      chip.className = "cpu-mode-chip";
      chip.textContent = "CPU READY";
      title.appendChild(chip);
    }
  }

  function labelButtons(){
    Object.keys(BUTTON_TEXT).forEach(function(action){
      $$('[data-action="' + action + '"], [data-table-action="' + action + '"]').forEach(function(btn){
        btn.textContent = BUTTON_TEXT[action];
      });
    });
  }

  function labelTiles(){
    $$(".casino-game-tile").forEach(function(tile){
      if(tile.querySelector(".cpu-mini")) return;
      var small = document.createElement("em");
      small.className = "cpu-mini";
      small.textContent = "CPU MODE";
      tile.appendChild(small);
    });
  }

  function updateDuckLine(){
    var status = $("#casinoStatus");
    var game = activeGame();
    if(status && !/CPU Mode/i.test(status.textContent || "")){
      status.textContent = 'Duck Sauce: “CPU Mode is ready. No waiting on another user — pick a game and play.”';
    }
    if(window.duckCpuModeLast !== game){
      window.duckCpuModeLast = game;
      setTimeout(function(){ renderPanel(); labelButtons(); }, 80);
    }
  }

  function run(){
    injectStyles();
    labelTiles();
    labelButtons();
    renderPanel();
    updateDuckLine();
  }

  function boot(){
    run();
    document.addEventListener("click", function(e){
      if(e.target.closest("[data-game], [data-action], [data-table-action]")){
        setTimeout(run, 90);
      }
    }, true);
    var observer = new MutationObserver(function(){ run(); });
    observer.observe(document.documentElement, { childList:true, subtree:true });
  }

  if(document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
})();
